import { jsPDF } from "jspdf";

export function exportDocumentToPdf(title, content, appName) {
  const doc = new jsPDF({
    orientation: "portrait",
    unit: "pt",
    format: "letter"
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 45;
  const maxLineWidth = pageWidth - (margin * 2);
  let cursorY = margin;

  // Header Title
  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.setTextColor(15, 23, 42); // slate-900
  doc.text(title, margin, cursorY);
  cursorY += 24;

  // Subtitle / App Reference
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.setTextColor(100, 116, 139); // slate-500
  doc.text(`Generated by LaunchLegal for ${appName} • ${new Date().toLocaleDateString()}`, margin, cursorY);
  cursorY += 15;

  // Divider Line
  doc.setDrawColor(226, 232, 240);
  doc.setLineWidth(1);
  doc.line(margin, cursorY, pageWidth - margin, cursorY);
  cursorY += 20;

  // Process text lines
  const rawLines = content.split("\n");
  
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10.5);
  doc.setTextColor(30, 41, 59); // slate-800

  for (let i = 0; i < rawLines.length; i++) {
    let line = rawLines[i].trim();

    // Check for page overflow
    if (cursorY > pageHeight - margin - 30) {
      doc.addPage();
      cursorY = margin + 15;
    }

    if (line.startsWith("# ")) {
      // Top level heading
      cursorY += 12;
      doc.setFont("helvetica", "bold");
      doc.setFontSize(14);
      doc.setTextColor(15, 23, 42);
      const text = line.replace(/^#\s+/, "");
      doc.text(text, margin, cursorY);
      cursorY += 18;
      doc.setFont("helvetica", "normal");
      doc.setFontSize(10.5);
      doc.setTextColor(30, 41, 59);
    } else if (line.startsWith("## ")) {
      // Sub-heading
      cursorY += 10;
      doc.setFont("helvetica", "bold");
      doc.setFontSize(12);
      doc.setTextColor(15, 23, 42);
      const text = line.replace(/^##\s+/, "");
      doc.text(text, margin, cursorY);
      cursorY += 16;
      doc.setFont("helvetica", "normal");
      doc.setFontSize(10.5);
      doc.setTextColor(30, 41, 59);
    } else if (line.startsWith("### ")) {
      // Level 3 heading
      cursorY += 6;
      doc.setFont("helvetica", "bold");
      doc.setFontSize(11);
      doc.setTextColor(30, 41, 59);
      const text = line.replace(/^###\s+/, "");
      doc.text(text, margin, cursorY);
      cursorY += 14;
      doc.setFont("helvetica", "normal");
      doc.setFontSize(10.5);
      doc.setTextColor(51, 65, 85);
    } else if (line === "---") {
      // Horizontal separator
      cursorY += 6;
      doc.setDrawColor(226, 232, 240);
      doc.line(margin, cursorY, pageWidth - margin, cursorY);
      cursorY += 12;
    } else if (line.length === 0) {
      cursorY += 8;
    } else {
      // Clean up markdown formatting for PDF output
      const cleanLine = line
        .replace(/\*\*(.*?)\*\*/g, "$1")
        .replace(/\*(.*?)\*/g, "$1")
        .replace(/\[(.*?)\]\((.*?)\)/g, "$1 ($2)");

      const wrappedLines = doc.splitTextToSize(cleanLine, maxLineWidth);
      for (const wLine of wrappedLines) {
        if (cursorY > pageHeight - margin - 20) {
          doc.addPage();
          cursorY = margin + 15;
        }
        doc.text(wLine, margin, cursorY);
        cursorY += 14;
      }
    }
  }

  // Add Page Numbers
  const totalPages = doc.internal.getNumberOfPages();
  for (let j = 1; j <= totalPages; j++) {
    doc.setPage(j);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);
    doc.setTextColor(148, 163, 184);
    doc.text(
      `Page ${j} of ${totalPages}`,
      pageWidth / 2,
      pageHeight - 20,
      { align: "center" }
    );
  }

  const safeFilename = `${appName.toLowerCase().replace(/[^a-z0-9]/g, "-")}-${title.toLowerCase().replace(/[^a-z0-9]/g, "-")}.pdf`;
  doc.save(safeFilename);
}
